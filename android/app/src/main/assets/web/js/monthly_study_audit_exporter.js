(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.MonthlyStudyAuditExporter = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const I18N_STRINGS = {
    en: {
      report_title: "Deep Focus — Monthly Study Audit",
      period_label: "Audit Period",
      executive_summary: "Executive Summary",
      total_study_time: "Total Focus Time",
      total_sessions: "Total Completed Sessions",
      daily_average: "Daily Average Focus",
      best_day: "Best Focus Day",
      focus_quality_avg: "Average Quality Score",
      category_breakdown: "Category & Subject Breakdown",
      category_col: "Category",
      sessions_col: "Sessions",
      duration_col: "Time (Hours)",
      share_col: "Share",
      daily_log_title: "Daily Focus Log",
      date_col: "Date",
      minutes_col: "Minutes",
      quality_col: "Quality",
      friction_col: "Top Distraction",
      friction_insights: "Distraction & Friction Audit",
      none_recorded: "None Recorded",
      footer_generated: "Generated by DEEP FOCUS — Zen Study & Focus Timer"
    },
    ar: {
      report_title: "ديب فوكس — التقرير الشهري الشامل للمدارسة والتركيز",
      period_label: "فترة التقرير",
      executive_summary: "الملخص التنفيذي",
      total_study_time: "إجمالي وقت التركيز",
      total_sessions: "إجمالي الجلسات المكتملة",
      daily_average: "المعدل اليومي للتركيز",
      best_day: "يوم الذروة في التركيز",
      focus_quality_avg: "متوسط مؤشر جودة التركيز",
      category_breakdown: "توزيع الجلسات حسب المادة والتصنيف",
      category_col: "المادة / التصنيف",
      sessions_col: "الجلسات",
      duration_col: "المدة (ساعات)",
      share_col: "النسبة",
      daily_log_title: "السجل اليومي للتركيز",
      date_col: "التاريخ",
      minutes_col: "الدقائق",
      quality_col: "الجودة",
      friction_col: "المشتت الأبرز",
      friction_insights: "تحليل المشتتات والمقاطعات",
      none_recorded: "لا يوجد",
      footer_generated: "تم إنشاء التقرير بواسطة DEEP FOCUS — مؤقت التركيز والمدارسة الهادئ"
    }
  };

  function sanitizeLocale(locale) {
    if (!locale || typeof locale !== 'string') return 'en';
    const clean = locale.toLowerCase().trim().split(/[-_]/)[0];
    if (clean === 'he' || clean === 'iw') {
      return 'en';
    }
    return clean;
  }

  function toWesternDigits(num, decimals = 0) {
    const val = Number(num);
    if (isNaN(val)) return '0';
    return decimals > 0 ? val.toFixed(decimals) : Math.round(val).toString();
  }

  function getLocalizedText(locale, key) {
    const clean = sanitizeLocale(locale);
    const dict = (clean === 'ar') ? I18N_STRINGS.ar : I18N_STRINGS.en;
    return dict[key] || I18N_STRINGS.en[key] || '';
  }

  function filterMonthSessions(sessions = [], monthKey = '2026-10') {
    if (!Array.isArray(sessions)) return [];
    return sessions.filter(s => {
      if (!s) return false;
      const dateStr = s.date || (s.startTime ? new Date(s.startTime).toISOString().slice(0, 10) : '');
      return typeof dateStr === 'string' && dateStr.startsWith(monthKey);
    });
  }

  function calculateMonthlyMetrics(sessions = [], monthKey = '2026-10') {
    const monthSessions = filterMonthSessions(sessions, monthKey);

    let totalDurationSeconds = 0;
    const categoryMap = {};
    const dailyMap = {};
    const frictionMap = {};
    let totalQualityScore = 0;
    let qualityRatedSessions = 0;

    monthSessions.forEach(s => {
      const dur = Math.max(0, parseInt(s.durationSeconds, 10) || 0);
      totalDurationSeconds += dur;

      const cat = (s.category && typeof s.category === 'string') ? s.category.trim() : 'General';
      if (!categoryMap[cat]) {
        categoryMap[cat] = { seconds: 0, sessions: 0 };
      }
      categoryMap[cat].seconds += dur;
      categoryMap[cat].sessions += 1;

      const date = s.date || (s.startTime ? new Date(s.startTime).toISOString().slice(0, 10) : monthKey + '-01');
      if (!dailyMap[date]) {
        dailyMap[date] = { seconds: 0, sessions: 0, qualitySum: 0, qualityCount: 0, frictions: {} };
      }
      dailyMap[date].seconds += dur;
      dailyMap[date].sessions += 1;

      if (s.qualityScore !== undefined && !isNaN(s.qualityScore)) {
        totalQualityScore += Number(s.qualityScore);
        qualityRatedSessions += 1;
        dailyMap[date].qualitySum += Number(s.qualityScore);
        dailyMap[date].qualityCount += 1;
      }

      const frictions = Array.isArray(s.frictionLogs) ? s.frictionLogs : [];
      frictions.forEach(f => {
        const type = f.type || 'OTHER';
        frictionMap[type] = (frictionMap[type] || 0) + 1;
        dailyMap[date].frictions[type] = (dailyMap[date].frictions[type] || 0) + 1;
      });
    });

    const totalHours = totalDurationSeconds / 3600;
    const activeDaysCount = Object.keys(dailyMap).length;
    const dailyAvgMinutes = activeDaysCount > 0 ? (totalDurationSeconds / activeDaysCount / 60) : 0;
    const avgQuality = qualityRatedSessions > 0 ? Math.round(totalQualityScore / qualityRatedSessions) : 85;

    let bestDay = 'None';
    let maxDaySeconds = -1;
    Object.keys(dailyMap).sort().forEach(d => {
      if (dailyMap[d].seconds > maxDaySeconds) {
        maxDaySeconds = dailyMap[d].seconds;
        bestDay = d;
      }
    });

    return {
      monthKey,
      totalSessions: monthSessions.length,
      totalDurationSeconds,
      totalHours: Number(totalHours.toFixed(2)),
      dailyAvgMinutes: Math.round(dailyAvgMinutes),
      activeDaysCount,
      avgQuality,
      bestDay,
      categoryMap,
      dailyMap,
      frictionMap
    };
  }

  function generateMarkdownReport(sessions, monthKey, locale = 'en') {
    const cleanLocale = sanitizeLocale(locale);
    const metrics = calculateMonthlyMetrics(sessions, monthKey);
    const t = (k) => getLocalizedText(cleanLocale, k);

    let md = '';

    md += `# ${t('report_title')}\n\n`;
    md += `**${t('period_label')}:** \`${metrics.monthKey}\`  \n`;
    md += `**${t('footer_generated')}**\n\n`;
    md += `---\n\n`;

    md += `## 📊 ${t('executive_summary')}\n\n`;
    md += `- **${t('total_study_time')}:** ${toWesternDigits(metrics.totalHours, 2)} hours (${toWesternDigits(Math.round(metrics.totalDurationSeconds / 60))} minutes)\n`;
    md += `- **${t('total_sessions')}:** ${toWesternDigits(metrics.totalSessions)}\n`;
    md += `- **${t('daily_average')}:** ${toWesternDigits(metrics.dailyAvgMinutes)} min / active day\n`;
    md += `- **${t('best_day')}:** \`${metrics.bestDay}\`\n`;
    md += `- **${t('focus_quality_avg')}:** ${toWesternDigits(metrics.avgQuality)} / 100\n\n`;

    md += `## 📚 ${t('category_breakdown')}\n\n`;
    md += `| ${t('category_col')} | ${t('sessions_col')} | ${t('duration_col')} | ${t('share_col')} |\n`;
    md += `| :--- | :---: | :---: | :---: |\n`;

    const catKeys = Object.keys(metrics.categoryMap).sort();
    if (catKeys.length === 0) {
      md += `| ${t('none_recorded')} | 0 | 0.00 | 0% |\n`;
    } else {
      catKeys.forEach(cat => {
        const item = metrics.categoryMap[cat];
        const hours = (item.seconds / 3600);
        const share = metrics.totalDurationSeconds > 0 ? Math.round((item.seconds / metrics.totalDurationSeconds) * 100) : 0;
        md += `| **${cat}** | ${toWesternDigits(item.sessions)} | ${toWesternDigits(hours, 2)} | ${toWesternDigits(share)}% |\n`;
      });
    }
    md += `\n`;

    md += `## 📅 ${t('daily_log_title')}\n\n`;
    md += `| ${t('date_col')} | ${t('sessions_col')} | ${t('minutes_col')} | ${t('quality_col')} |\n`;
    md += `| :--- | :---: | :---: | :---: |\n`;

    const dayKeys = Object.keys(metrics.dailyMap).sort();
    if (dayKeys.length === 0) {
      md += `| ${metrics.monthKey}-01 | 0 | 0 | - |\n`;
    } else {
      dayKeys.forEach(d => {
        const dayItem = metrics.dailyMap[d];
        const dayMinutes = Math.round(dayItem.seconds / 60);
        const dayQuality = dayItem.qualityCount > 0 ? Math.round(dayItem.qualitySum / dayItem.qualityCount) : '-';
        md += `| \`${d}\` | ${toWesternDigits(dayItem.sessions)} | ${toWesternDigits(dayMinutes)} | ${dayQuality !== '-' ? toWesternDigits(dayQuality) : '-'} |\n`;
      });
    }
    md += `\n`;

    md += `## 🔍 ${t('friction_insights')}\n\n`;
    const frictionKeys = Object.keys(metrics.frictionMap);
    if (frictionKeys.length === 0) {
      md += `*${t('none_recorded')}*\n`;
    } else {
      frictionKeys.sort((a, b) => metrics.frictionMap[b] - metrics.frictionMap[a]).forEach(f => {
        md += `- **${f}:** ${toWesternDigits(metrics.frictionMap[f])} occurrences\n`;
      });
    }

    return md;
  }

  return {
    sanitizeLocale,
    toWesternDigits,
    filterMonthSessions,
    calculateMonthlyMetrics,
    generateMarkdownReport,
    getLocalizedText
  };
}));
