/**
 * DEEP FOCUS — Weekly Smart Study Notes Digest Engine
 * Cycle: CYCLE-116 (Mission #116)
 * Architecture: v21 Data Fortress Safe, Study Synthesis & Markdown Digest Exporter
 * Strict Rules:
 *  - 100-Locale Support with Strict English-Only Fallback
 *  - Absolute Hebrew Exclusion (he, iw -> en)
 *  - Strict Western Digits 0123456789
 *  - 100% Offline (Local Markdown & JSON Digest)
 */

(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.WeeklyStudyNotesDigestEngine = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const I18N_STRINGS = {
    en: {
      digest_title: "Deep Focus — Weekly Study Notes Digest",
      period_label: "Review Window",
      total_notes_label: "Total Key Notes Captured",
      categories_covered_label: "Categories Studied",
      top_tags_label: "Core Themes & Tags",
      checklist_title: "Active Recall Consolidation Checklist",
      empty_notes_notice: "No session notes captured for this weekly period.",
      footer_generated: "Generated by DEEP FOCUS — Zen Study & Focus Timer"
    },
    ar: {
      digest_title: "ديب فوكس — الحصيلة الأسبوعية لفوائد وملاحظات المدارسة",
      period_label: "فترة المراجعة",
      total_notes_label: "إجمالي الفوائد والملاحظات المسجلة",
      categories_covered_label: "المواد والتصنيفات المدروسة",
      top_tags_label: "المحاور والوسوم الأساسية",
      checklist_title: "قائمة التحقق لتثبيت ومراجعة الاسترجاع",
      empty_notes_notice: "لم يتم تدوين ملاحظات خلال هذه الفترة الأسبوعية.",
      footer_generated: "تم إنشاء التلخيص بواسطة DEEP FOCUS — مؤقت التركيز والمدارسة الهادئ"
    }
  };

  function sanitizeLocale(locale) {
    if (!locale || typeof locale !== 'string') return 'en';
    const clean = locale.toLowerCase().trim().split(/[-_]/)[0];
    if (clean === 'he' || clean === 'iw') {
      return 'en';
    }
    return clean;
  }

  function toWesternDigits(num, decimals = 0) {
    const val = Number(num);
    if (isNaN(val)) return '0';
    return decimals > 0 ? val.toFixed(decimals) : Math.round(val).toString();
  }

  function getLocalizedText(locale, key) {
    const clean = sanitizeLocale(locale);
    const dict = (clean === 'ar') ? I18N_STRINGS.ar : I18N_STRINGS.en;
    return dict[key] || I18N_STRINGS.en[key] || '';
  }

  function extractTags(text) {
    if (!text || typeof text !== 'string') return [];
    const matches = text.match(/#[a-zA-Z0-9_\u0600-\u06FF]+/g);
    return matches ? matches.map(t => t.toLowerCase()) : [];
  }

  function aggregateWeeklyNotes(notesList = [], startDateStr, endDateStr) {
    const list = Array.isArray(notesList) ? notesList : [];
    const filtered = list.filter(n => {
      if (!n || !n.text) return false;
      const date = n.date || (n.timestamp ? new Date(n.timestamp).toISOString().slice(0, 10) : '');
      if (startDateStr && date < startDateStr) return false;
      if (endDateStr && date > endDateStr) return false;
      return true;
    });

    const categoryMap = {};
    const tagCounts = {};

    filtered.forEach(item => {
      const cat = (item.category && typeof item.category === 'string') ? item.category.trim() : 'General';
      if (!categoryMap[cat]) {
        categoryMap[cat] = [];
      }
      categoryMap[cat].push({
        id: item.id || `n_${Date.now()}`,
        text: item.text.trim(),
        date: item.date || '',
        tags: extractTags(item.text)
      });

      const tags = extractTags(item.text);
      tags.forEach(t => {
        tagCounts[t] = (tagCounts[t] || 0) + 1;
      });
    });

    const topTags = Object.keys(tagCounts).sort((a, b) => tagCounts[b] - tagCounts[a]);

    return {
      totalNotes: filtered.length,
      categoryMap,
      tagCounts,
      topTags,
      categoriesCount: Object.keys(categoryMap).length
    };
  }

  function generateWeeklyDigestMarkdown(notesList, startDateStr, endDateStr, locale = 'en') {
    const cleanLocale = sanitizeLocale(locale);
    const t = (k) => getLocalizedText(cleanLocale, k);
    const summary = aggregateWeeklyNotes(notesList, startDateStr, endDateStr);

    let md = '';
    md += `# 📝 ${t('digest_title')}\n\n`;
    md += `**${t('period_label')}:** \`${startDateStr}\` → \`${endDateStr}\`  \n`;
    md += `**${t('footer_generated')}**\n\n`;
    md += `---\n\n`;

    md += `### 📌 Overview\n\n`;
    md += `- **${t('total_notes_label')}:** ${toWesternDigits(summary.totalNotes)}\n`;
    md += `- **${t('categories_covered_label')}:** ${toWesternDigits(summary.categoriesCount)}\n\n`;

    if (summary.topTags.length > 0) {
      md += `**${t('top_tags_label')}:** ` + summary.topTags.map(tag => `\`${tag}\` (${toWesternDigits(summary.tagCounts[tag])})`).join(', ') + `\n\n`;
    }

    if (summary.totalNotes === 0) {
      md += `*${t('empty_notes_notice')}*\n\n`;
      return md;
    }

    Object.keys(summary.categoryMap).sort().forEach(cat => {
      const notes = summary.categoryMap[cat];
      md += `### 📚 ${cat} (${toWesternDigits(notes.length)})\n\n`;
      notes.forEach(n => {
        const dateTag = n.date ? `_(${n.date})_ ` : '';
        md += `- ${dateTag}${n.text}\n`;
      });
      md += `\n`;
    });

    md += `### ✅ ${t('checklist_title')}\n\n`;
    Object.keys(summary.categoryMap).sort().forEach(cat => {
      md += `- [ ] Consolidate & self-test core concepts in **${cat}**\n`;
    });
    md += `\n`;

    return md;
  }

  return {
    extractTags,
    aggregateWeeklyNotes,
    generateWeeklyDigestMarkdown,
    sanitizeLocale,
    toWesternDigits,
    getLocalizedText
  };
}));
