/**
 * Deep Focus critical room 7 — task W04 contract tests.
 *
 * W04 develops an OFFLINE parser/assertion helper for Android SAF CSV export
 * evidence: actual selected filename, content (quoting/CRLF/BOM), cancel vs
 * save receipts, Western digits in system fields, and DST-safe credited dates.
 *
 * The one reproduced defect, proven against the current integrated v21 code:
 * a SAF CSV payload that starts with U+FEFF (BOM) is rejected by the native
 * gate `csv.startsWith("\"id\"")` in MainActivity.exportAnalyticsCsvToFile,
 * which surfaces to the user as a "failed" export although the CSV content
 * itself is valid (the browser Blob fallback in analytics_studio.js prepends
 * a BOM). The probe must detect and classify that evidence defect offline.
 *
 * Every test here is an offline Node source audit on captured-style evidence.
 * This is NOT Android verification; no device result is claimed.
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');
