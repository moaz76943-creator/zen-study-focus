/* ---------- RED repro: the real BOM-vs-native-gate defect ---------- */

test('RED repro: BOM-prefixed SAF CSV is a confirmed export defect (native startsWith gate rejects it)', async () => {
  const probe = await IMPORT();
  const bomCsv = '\uFEFF' + SESSIONS_CSV;
  // Live fact being modeled: MainActivity requires csv.startsWith("\"id\"").
  assert.equal(bomCsv.startsWith('"id"'), false, 'live gate must reject a BOM payload');

  const report = probe.evaluateEvidence([{
    requestId: 'df-csv-1770000000007',
    resultCode: -1,
    receipt: 'failed',
    uri: 'content://downloads/documents/' + SUGGESTED,
    csv: bomCsv,
    kind: 'sessions'
  }]);

  assert.equal(report.status, 'FAIL');
  const bom = report.confirmedDefects.find(d => d.id === 'BOM_ON_SAF_EXPORT');
  assert.ok(bom, 'BOM_ON_SAF_EXPORT defect must be confirmed');
  assert.match(bom.detail, /startsWith/);
  const entry = report.entries[0];
  assert.equal(entry.content.ok, false);
  assert.ok(entry.violationIds.includes('BOM_ON_SAF_EXPORT'));
  // Clean csv evidence of the same export parses fine: the defect is the BOM.
  assert.equal(probe.parseCsvEvidence(SESSIONS_CSV, { kind: 'sessions' }).ok, true);
});

