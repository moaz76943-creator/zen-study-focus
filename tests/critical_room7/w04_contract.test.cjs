/* ---------- Western digits vs preserved user-authored text ---------- */

test('RED repro: Eastern digits inside system date fields are flagged; user id text is preserved', async () => {
  const probe = await IMPORT();
  const eastern = '"id","date","domain","minutes","startedAt","endedAt","timingVerified"\r\n' +
    '"الملاحظة ١٢","٢٠٢٦-١٠-٢٢","read","١٨","","","false"\r\n';
  const parsed = probe.parseCsvEvidence(eastern, { kind: 'sessions' });
  assert.equal(parsed.ok, false);
  assert.ok(parsed.violationIds.includes('NON_WESTERN_SYSTEM_DIGITS'));
  const digitRows = parsed.rows
    .map(r => probe.auditSystemDigits(r, ['id', 'date', 'domain', 'minutes', 'startedAt', 'endedAt', 'timingVerified'], ['id']));
  const flags = digitRows.flatMap(r => r.violations);
  assert.ok(flags.length >= 2, 'date and at least one other system cell must be flagged');
  assert.ok(flags.some(f => f.field === 'date'), 'the credited date is a system field');
  // User-authored id is preserved verbatim and never rewritten by the probe.
  assert.equal(digitRows.some(r => r.violations.some(f => f.field === 'id')), false);
  assert.equal(parsed.rows[0][0], 'الملاحظة ١٢');
});

/* ---------- DST dates: credited local dates survive 23h/25h local days ---------- */

test('no credit column may drift across a 25-hour local fall-back day', async () => {
  const probe = await IMPORT();

  // Real wall-clock lengths of the DST days (fixed offsets, offline, no zone DB):
  const fall25h = Date.parse('2026-11-02T00:30:00-05:00') - Date.parse('2026-11-01T00:30:00-04:00');
  const spring23h = Date.parse('2027-03-15T00:30:00-04:00') - Date.parse('2027-03-14T00:30:00-05:00');
  assert.equal(fall25h, 25 * 3600000, 'the local day really has 25 hours');
  assert.equal(spring23h, 23 * 3600000, 'the local day really has 23 hours');

  // The probe's v21 noon-anchor arithmetic must be immune to all of that:
  // each consecutive credited run steps by exactly one UTC-noon day.
  const fallRun = probe.verifyDayAnchors(['2026-10-31', '2026-11-01', '2026-11-02']);
  const springRun = probe.verifyDayAnchors(['2027-03-13', '2027-03-14', '2027-03-15']);
  assert.equal(fallRun.status, 'PASS');
  assert.equal(springRun.status, 'PASS');
  for (const checked of [fallRun, springRun]) {
    assert.ok(checked.gaps.every(g => g.gapMs === 86400000), 'every pair is exactly one UTC-noon anchor day');
    assert.match(checked.note, /noon/);
  }
  const badRun = probe.verifyDayAnchors(['2026-11-01', '2027-03-14']);
  assert.equal(badRun.status, 'FAIL', 'a non-consecutive credited run is not a valid day sequence');
});

