test('receipt/resultCode mismatch is a confirmed evidence defect in both directions', async () => {
  const probe = await IMPORT();
  const report = probe.evaluateEvidence([
    { ...CANCEL_EVIDENCE, receipt: 'saved', csv: SESSIONS_CSV }, // cancelled but bytes were written
    { ...SAVE_EVIDENCE, cause: 'clean save', requestId: 'df-csv-1770000000004', receipt: 'cancelled', csv: '' }
  ]);
  assert.equal(report.status, 'FAIL');
  const ids = report.confirmedDefects.map(d => d.id);
  assert.ok(ids.includes('RESULT_RECEIPT_MISMATCH'));
  assert.equal(report.entries[0].status, 'FAIL');
  assert.equal(report.entries[1].status, 'FAIL');
});

