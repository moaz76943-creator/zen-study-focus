#!/usr/bin/env node
// Android WebView loads the app from file:///android_asset with file access locked down, so
// fetch()/XHR of locales/*.json and locale_packs/*.json are refused on a real device
// (they only work over http in a desktop browser). This script inlines the same JSON into a
// classic script that the loaders consult first.   node tools/build_locale_bundle.mjs [--check]
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '../android/app/src/main/assets/web');
const out = join(web, 'locale_packs/locale_bundle.js');
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

const bundle = { packs: {}, files: {} };
const packDir = join(web, 'locale_packs');
for (const f of readdirSync(packDir).filter((n) => n.endsWith('.json')).sort()) bundle.packs[f] = readJson(join(packDir, f));
const fileDir = join(web, 'locales');
for (const f of readdirSync(fileDir).filter((n) => n.endsWith('.json')).sort()) bundle.files[f.replace(/\.json$/, '')] = readJson(join(fileDir, f));

const body = '/* GENERATED by tools/build_locale_bundle.mjs - do not edit. Mirrors locales/*.json and locale_packs/*.json\n' +
  '   for the Android WebView, where fetch()/XHR of file:// assets is blocked. */\n' +
  'window.__DF_LOCALE_BUNDLE = ' + JSON.stringify(bundle) + ';\n';

if (process.argv.includes('--check')) {
  const same = existsSync(out) && readFileSync(out, 'utf8') === body;
  if (!same) { console.error('locale_bundle.js is stale: run node tools/build_locale_bundle.mjs'); process.exit(1); }
  console.log('locale_bundle.js is up to date');
} else {
  writeFileSync(out, body);
  console.log('wrote', out, (body.length / 1024).toFixed(0) + ' KB');
}
