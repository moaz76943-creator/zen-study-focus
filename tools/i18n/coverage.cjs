'use strict';
// Coverage report for the 100 official languages against i18n/source_en.json -> i18n/COVERAGE.md + stdout JSON.
const fs = require('fs'), path = require('path');
const repo = path.resolve(__dirname, '../..');
const src = Object.keys(JSON.parse(fs.readFileSync(path.join(repo, 'i18n/source_en.json'), 'utf8')));
const reg = JSON.parse(fs.readFileSync(path.join(repo, 'i18n/languages.json'), 'utf8'));
const rows = [];
for (const l of reg.languages) {
  if (l.code === 'en') { rows.push({ code: 'en', name: l.enName, status: 'source', translated: src.length, missing: 0, sameAsEnglish: 0, pct: 100 }); continue; }
  const f = path.join(repo, 'i18n/packs', l.code + '.json');
  if (!fs.existsSync(f)) { rows.push({ code: l.code, name: l.enName, status: 'no-pack', translated: 0, missing: src.length, sameAsEnglish: 0, pct: 0 }); continue; }
  const p = JSON.parse(fs.readFileSync(f, 'utf8')); const t = p.t || {};
  const tr = src.filter((k) => typeof t[k] === 'string' && t[k].trim());
  const same = tr.filter((k) => t[k] === k && /[A-Za-z]{3}/.test(k)).length;
  rows.push({ code: l.code, name: l.enName, status: p.status, translated: tr.length, missing: src.length - tr.length, sameAsEnglish: same, pct: Math.floor(100 * tr.length / src.length) });
}
const md = ['# UI catalog coverage', '', 'Generated by `node tools/i18n/coverage.cjs`. Source strings: ' + src.length + '. Status "ai-pending-review" means AI-translated and NOT reviewed by a person.', '', '| Code | Language | Status | Translated | Missing | Identical to English | % |', '|---|---|---|---|---|---|---|']
  .concat(rows.map((r) => `| ${r.code} | ${r.name} | ${r.status} | ${r.translated} | ${r.missing} | ${r.sameAsEnglish} | ${r.pct} |`));
fs.writeFileSync(path.join(repo, 'i18n/COVERAGE.md'), md.join('\n') + '\n');
const full = rows.filter((r) => r.pct === 100).length;
console.log(JSON.stringify({ sourceStrings: src.length, languages: rows.length, complete: full, withPack: rows.filter((r) => r.status !== 'no-pack').length }));
